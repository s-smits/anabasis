/**
 * What one machine holds of what `bun run runs sync` keeps in step, read and changed nowhere. On a
 * peer this file runs bundled, piped to that machine's Bun over ssh (`sync.ts`): the verbs a peer
 * could be asked run from a controller, which a preparation writes to the peer, or from its configured
 * tree at whatever commit that holds, and a dry run writes nothing and reads with today's code. So it
 * keeps to what a bundle can carry and starts no verb.
 *
 * It reads `.env.runs` and no other env file. A key sync does not carry is named and its value is
 * never printed, and in a file sync did not generate every key is, so a hand-written file that holds
 * a credential gives its name alone. What a solve finds is `hostPython`: the first `python3` on the
 * wall's path, which a login shell's `python3` need not be.
 */
import { existsSync, readFileSync } from "#src/meta/filesystem.ts";
import { sha256 } from "#src/meta/digest.ts";
import { capturedJsonStringify, parseJsonAs } from "#src/meta/json-runtime.ts";
import { asRecord, isString } from "#src/meta/json-shape.ts";
import { homedir } from "#src/meta/os.ts";
import { join } from "#src/meta/path.ts";
import { parseArgs, runtimeProcess } from "#src/meta/process.ts";
import { compareCodeUnits } from "#src/meta/stable-json.ts";
import { decodeOutput, runSync } from "#src/meta/subprocess.ts";
import { toolchainPathDirs } from "#src/wall/policy.ts";
import { RECEIPT, RUN_SCRIPT, RUNNER_FILES } from "../runtime/router/payload.ts";

/** The first `python3` on the wall's path, with the packages it holds whoever runs it. */
export interface HostPython {
  readonly version: string;
  /** Each as `name==version`, sorted. */
  readonly packages: readonly string[];
}

/** What `.env.runs` in a tree holds, and for a generated one the values of what sync carries. */
interface SettingsFile {
  readonly header: string;
  readonly generated: boolean;
  readonly values: Readonly<Record<string, string>>;
  /** Every key whose value this read left out. */
  readonly others: readonly string[];
}

export interface HostFacts {
  readonly settings: SettingsFile | null;
  readonly python: HostPython | null;
  /** Which `python3` that is, as the wall's path finds it. */
  readonly pythonPath: string | null;
  /** The `uv` a sync would run here, and its version. */
  readonly uv: { readonly path: string; readonly version: string } | null;
  /** Whether that `uv` offers the wanted Python, null where none was wanted or `uv` did not say. */
  readonly offered: boolean | null;
  /** The `python-` lines of the home's `uv.toml`, which a seat's `uv` does not read. */
  readonly uvConfig: readonly string[];
  /** Each installed runner file's digest, by name, and the commit it came from. */
  readonly runner: {
    readonly files: Readonly<Record<string, string>>;
    readonly commit: string | null;
  } | null;
}

/** The first words of a generated `.env.runs`. */
export const GENERATED = "# Generated by `bun run runs sync`";
/** What sync carries, by name. Nothing else reaches another machine. */
export const CARRIED: readonly string[] = [
  "ANA_KEEP",
  "ANA_LOGINS",
  "ANA_LOGIN_RUNS",
  "ANA_LOGIN_SUBS",
  "ANA_RUN_CAP",
  "ANA_SEARCH_ROOTS",
];
export const SETTINGS_FILE = ".env.runs";
/** The router's own file, kept beside the runner's folder under `~/.local/bin`. */
export const ROUTER = "bun";

/** Prints a Python's version and packages. Run with `-I`: a solve's home is its own, so the user's
 *  site packages and `PYTHONPATH` of the shell that launched a run are none of what a solve finds. */
const PYTHON_PROBE = `import importlib.metadata as m, json, sys
print(json.dumps([sys.version.split()[0], [d.metadata["Name"] + "==" + d.version for d in m.distributions()]]))`;
const PYTHON_SECONDS = 10;
const UV_SECONDS = 20;

const firstOn = (dirs: readonly string[], name: string): string | undefined =>
  dirs.map((dir) => join(dir, name)).find((file) => existsSync(file));

/** What the first `python3` among `dirs` is and holds, or null where none is there or it does not
 *  answer. A launch goes on either way: this is a fact for reading, and it decides nothing. */
export function hostPython(dirs: readonly string[] = toolchainPathDirs()): HostPython | null {
  const path = firstOn(dirs, "python3");
  if (path === undefined) return null;
  const { exitCode, stdout } = runSync([path, "-I", "-c", PYTHON_PROBE], {
    timeout: PYTHON_SECONDS * 1000,
  });
  if (exitCode !== 0) return null;
  try {
    const [version, packages] = parseJsonAs<[string, string[]]>(decodeOutput(stdout));
    return { version, packages: packages.toSorted(compareCodeUnits) };
  } catch {
    // A program named python3 that prints something else is no Python this can read.
    return null;
  }
}

/** A runner file's digest. A bundle's comments name each source by its path from where it was built,
 *  so one tree's `hosts.js` built in two folders differs by those lines alone. */
export const runnerDigest = (name: string, text: string): string =>
  sha256(name === "hosts.js" ? text.replaceAll(/^\/\/ (?!@bun).*\.ts\n/gmu, "") : text);

export function settingsIn(text: string): SettingsFile {
  const [header = ""] = text.split("\n");
  const generated = header.startsWith(GENERATED);
  const values: Record<string, string> = {};
  const others: string[] = [];
  for (const line of text.split("\n")) {
    const [, key, value] = /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)=(.*)$/u.exec(line) ?? [];
    if (key === undefined || value === undefined) continue;
    if (generated && CARRIED.includes(key)) {
      values[key] = value.replace(/^'(.*)'$/u, "$1").replaceAll(String.raw`\$`, "$");
    } else {
      others.push(key);
    }
  }
  return { header: generated ? header : "", generated, values, others };
}

const textAt = (path: string): string | null => (existsSync(path) ? readFileSync(path, "utf8") : null);

function runnerAt(home: string): HostFacts["runner"] {
  const dir = join(home, ".local", "share", "ana-runner");
  if (!existsSync(join(dir, RUN_SCRIPT))) return null;
  const files: Record<string, string> = {};
  for (const name of RUNNER_FILES) {
    const text = textAt(join(dir, name));
    if (text !== null) files[name] = runnerDigest(name, text);
  }
  const router = textAt(join(home, ".local", "bin", ROUTER));
  if (router !== null) files[ROUTER] = runnerDigest(ROUTER, router);
  let commit: string | null = null;
  try {
    const said = asRecord(parseJsonAs<unknown>(textAt(join(dir, RECEIPT)) ?? "null"))?.commit;
    commit = isString(said) ? said : null;
  } catch {
    // A receipt that does not parse names no commit; the digests still say what differs.
  }
  return { files, commit };
}

function answer(cmd: readonly string[]): string | null {
  const { exitCode, stdout } = runSync(cmd, { timeout: UV_SECONDS * 1000 });
  return exitCode === 0 ? decodeOutput(stdout).trim() : null;
}

/** The facts of this machine, for the tree at the current folder. `uv` is the one a sync would run,
 *  a path or a name on the PATH, and `wanted` the Python a pin asks for. */
export function hostFacts(uv: string, wanted: string | undefined): HostFacts {
  const home = homedir();
  const path = uv.startsWith("~/") ? join(home, uv.slice(2)) : (Bun.which(uv) ?? uv);
  const version = answer([path, "--version"])?.split(" ")[1];
  // Read from what is on hand: no download, no cache, no config, so the answer changes nothing here.
  const listed =
    wanted === undefined || version === undefined
      ? null
      : answer([
          path,
          "--no-config",
          "--no-cache",
          "--offline",
          "python",
          "list",
          "--managed-python",
          "--all-versions",
          wanted,
        ]);
  const settings = textAt(SETTINGS_FILE);
  const dirs = toolchainPathDirs(home);
  return {
    settings: settings === null ? null : settingsIn(settings),
    python: hostPython(dirs),
    pythonPath: firstOn(dirs, "python3") ?? null,
    uv: version === undefined ? null : { path, version },
    // A PyPy of the same version is no CPython to install: `uv` lists both.
    offered: listed === null ? null : /^cpython-/mu.test(listed),
    uvConfig: (textAt(join(home, ".config", "uv", "uv.toml")) ?? "")
      .split("\n")
      .filter((line) => line.startsWith("python-")),
    runner: runnerAt(home),
  };
}

if (import.meta.main) {
  const { values } = parseArgs({
    args: runtimeProcess.argv.slice(2),
    options: { uv: { type: "string", default: "uv" }, python: { type: "string" } },
  });
  console.log(capturedJsonStringify(hostFacts(values.uv, values.python)));
}
